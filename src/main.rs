use std::sync::Arc;

use clap::{Parser, Subcommand};
use tracing::info;

use rupoo::agent::safety::SafetyContext;
use rupoo::agent::Agent;
use rupoo::db::TaskRepo;
use rupoo::mcp::McpToolExecutor;
use rupoo::skill::SkillManager;
