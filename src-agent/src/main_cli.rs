/// Manage and install external tools (MCP servers, search engines, etc.)
#[derive(clap::Subcommand)]
pub enum ToolsAction {
    /// Install cortex-scout MCP server for web search + page extraction
    InstallCortexScout {
        /// Version to install (default: latest)
        #[arg(long)]
        version: Option<String>,
    },
    /// List installed tools and their status
    Status,
}

#[derive(clap::Subcommand)]
pub enum LoopAction {
    /// Start a new adaptive loop
    Start {
        /// Goal / task description
        goal: String,
        /// Max iterations (default: 10)
        #[arg(long, default_value_t = 10)]
        max_iterations: u32,
        /// Token budget limit
        #[arg(long)]
        token_budget: Option<u64>,
        /// Time budget in seconds
        #[arg(long)]
        time_budget: Option<u64>,
    },
    /// Show loop status
    Status {
        /// Loop ID
        id: String,
    },
    /// List all loops
    List {
        /// Maximum loops to show
        #[arg(long, default_value_t = 20)]
        limit: usize,
    },
    /// Pause a running loop
    Pause {
        /// Loop ID
        id: String,
    },
    /// Resume a paused loop
    Resume {
        /// Loop ID
        id: String,
    },
    /// Cancel a loop
    Cancel {
        /// Loop ID
        id: String,
    },
}

