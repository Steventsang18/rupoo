async fn handle_tools_action(action: ToolsAction) -> anyhow::Result<()> {
    match action {
        ToolsAction::InstallCortexScout { version } => {
            install_cortex_scout(version.as_deref()).await?;
        }
        ToolsAction::Status => {
            check_tools_status().await?;
        }
    }
    Ok(())
}

/// Install cortex-scout MCP server binary.
async fn install_cortex_scout(version: Option<&str>) -> anyhow::Result<()> {
    let rupoo_home = rupoo::config::rupoo_home();
    let bin_dir = rupoo_home.join("bin");
    std::fs::create_dir_all(&bin_dir)?;

    let ver = version.unwrap_or("3.3.7");
    let arch = if cfg!(target_arch = "aarch64") {
        "arm64"
    } else {
        "x86_64"
    };
    let os = if cfg!(target_os = "macos") {
        "macos"
    } else {
        "linux"
    };
    let filename = format!("cortex-scout-{ver}-{os}-{arch}.tar.gz");
    let url =
        format!("https://github.com/cortex-works/cortex-scout/releases/download/v{ver}/{filename}");

    let binary_name = if cfg!(target_os = "windows") {
        "cortex-scout-mcp.exe"
    } else {
        "cortex-scout-mcp"
    };
    let binary_path = bin_dir.join(binary_name);

    if binary_path.exists() {
        println!(
            "cortex-scout already installed at: {}",
            binary_path.display()
        );
        println!("  Run `rupoo tools install-cortex-scout` again to reinstall.");
        return Ok(());
    }

    println!("Downloading cortex-scout v{} for {}-{}...", ver, os, arch);
    println!("  URL: {}", url);

    // Download via reqwest
    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(300))
        .build()?;
    let response = client.get(&url).send().await?;

    if !response.status().is_success() {
        anyhow::bail!("Download failed: HTTP {}", response.status());
    }

    let bytes = response.bytes().await?;
    let temp_dir = std::env::temp_dir().join(format!("cortex-scout-{ver}"));
    std::fs::create_dir_all(&temp_dir)?;
    let tarball_path = temp_dir.join(&filename);

    std::fs::write(&tarball_path, &bytes)?;
    println!("  Downloaded {} MB", bytes.len() / 1_048_576);

    // Extract tarball
    let file = std::fs::File::open(&tarball_path)?;
    let decoder = flate2::read::GzDecoder::new(file);
    let mut archive = tar::Archive::new(decoder);

    for entry in archive.entries()? {
        let mut entry = entry?;
        let path = entry.path()?.to_path_buf();
        if let Some(name) = path.file_name() {
            if name == binary_name {
                entry.unpack(&binary_path)?;
                break;
            }
        }
    }

    // Make executable
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&binary_path, std::fs::Permissions::from_mode(0o755))?;
    }

    println!("  Installed: {}", binary_path.display());

    // Write MCP config
    let config_path = rupoo_home.join("config.toml");
    let config_content = if config_path.exists() {
        std::fs::read_to_string(&config_path)?
    } else {
        String::new()
    };

    if !config_content.contains("[mcp.servers.cortex-scout]") {
        let mcp_config = format!(
            r#"
[mcp.servers.cortex-scout]
command = "{}"
args = []
env = {{ SEARCH_ENGINES = "google,bing,duckduckgo,brave" }}
"#,
            binary_path.display()
        );
        std::fs::write(&config_path, config_content + &mcp_config)?;
        println!("  Added to config: {}", config_path.display());
    } else {
        println!("  MCP config already exists in: {}", config_path.display());
    }

    println!("\n✅ cortex-scout installed! Restart rupoo to use it.");
    println!("  Agent will now have `web_search` and `web_fetch` tools via MCP.");

    // Cleanup
    let _ = std::fs::remove_dir_all(&temp_dir);

    Ok(())
}

/// Check status of installed tools.
async fn check_tools_status() -> anyhow::Result<()> {
    let rupoo_home = rupoo::config::rupoo_home();

    println!("Tools status:");
    println!();

    // Check cortex-scout
    let scout_path = rupoo_home.join("bin/cortex-scout-mcp");
    if scout_path.exists() {
        println!(
            "  ✅ cortex-scout     installed at: {}",
            scout_path.display()
        );
        // Check MCP config
        let config_path = rupoo_home.join("config.toml");
        if config_path.exists() {
            let content = std::fs::read_to_string(&config_path)?;
            if content.contains("cortex-scout") {
                println!("     MCP config:      configured");
            } else {
                println!(
                    "     MCP config:      NOT configured (run `rupoo tools install-cortex-scout`)"
                );
            }
        }
    } else {
        println!("  ❌ cortex-scout     not installed");
        println!("     Install: `rupoo tools install-cortex-scout`");
    }

    Ok(())
}

async fn handle_loop_action(db: String, action: LoopAction) -> anyhow::Result<()> {
    let (_repo, agent, _) = crate::build_engine::build_engine(&db).await?;
    let agent = Arc::new(agent);

    let engine = agent
        .loop_engine
        .as_ref()
        .ok_or_else(|| anyhow::anyhow!("loop engine not initialized"))?;

    match action {
        LoopAction::Start {
            goal,
            max_iterations,
            token_budget,
            time_budget,
        } => {
            let config = LoopConfig {
                max_iterations,
                token_budget,
                time_budget_secs: time_budget,
                autonomy_level: rupoo::loop_engine::AutonomyLevel::L4AutoCorrect,
                ..Default::default()
            };

            println!("Starting loop: \"{}\"", goal);
            println!("  Max iterations: {}", max_iterations);

            let loop_result = engine
                .start_loop(&goal, config, Arc::clone(&agent), agent.llm_gateway_ref())
                .await?;

            println!("\nLoop finished:");
            println!("  ID: {}", loop_result.id);
            println!("  Status: {:?}", loop_result.status);
        }

        LoopAction::Status { id } => {
            let l = engine.get_loop_status(&id).await?;
            println!("Loop: {}", l.id);
            println!("  Goal: \"{}\"", l.goal);
            println!("  Status: {:?}", l.status);
            println!(
                "  Config: max_iters={}, autonomy={:?}",
                l.config.max_iterations, l.config.autonomy_level
            );
        }

        LoopAction::List { limit } => {
            let loops = engine.list_loops(limit, 0).await?;
            if loops.is_empty() {
                println!("No loops found.");
            } else {
                println!("Loops:");
                for l in &loops {
                    println!(
                        "  {} | {:?} | \"{}\"",
                        &l.id[..8.min(l.id.len())],
                        l.status,
                        &l.goal[..60.min(l.goal.len())]
                    );
                }
            }
        }

        LoopAction::Pause { id } => {
            engine.pause_loop(&id).await?;
            println!("Loop {} paused.", id);
        }

        LoopAction::Resume { id } => {
            println!("Resuming loop {}...", id);
            let l = engine
                .resume_loop(&id, Arc::clone(&agent), agent.llm_gateway_ref())
                .await?;
            println!("  Status: {:?}", l.status);
        }

        LoopAction::Cancel { id } => {
            engine.cancel_loop(&id).await?;
            println!("Loop {} cancelled.", id);
        }
    }

    Ok(())
}
